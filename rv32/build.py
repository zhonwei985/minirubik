#!/usr/bin/env python3
"""Turns rv32/minirubik.S into one file the Ripes assembler accepts.

Ripes (v2.2.6-106-g5b8a616) has no .include and no .if, so this inlines
the first and resolves the second against the .equ values. It can
also replace the query and drop the test list, which is how single-state
measurements are made.

  build.py                              writes rv32/ripes_cli.s, and
                                        rv32/ripes_gui.s with RENDER=1
  build.py OUT [--query STATE] [--no-tests] [--set NAME=VALUE]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "minirubik.S")


def inline(path):
    out = []
    for line in open(path, encoding="utf-8"):
        m = re.match(r'\s*\.include\s+"([^"]+)"', line)
        if m:
            out.extend(inline(os.path.join(HERE, m.group(1))))
        else:
            out.append(line.rstrip("\n"))
    return out


def conditionals(lines, sets):
    """Resolve .if NAME / .else / .endif using the .equ values seen so far,
    as GNU as would. sets overrides an .equ value (e.g. MOD3_BRANCH=0)."""
    values, out, stack = {}, [], []
    for line in lines:
        code = line.split("#", 1)[0].strip()
        m = re.match(r"\.equ\s+(\w+)\s*,\s*(\S+)$", code)
        if m and all(stack):
            name, value = m.group(1), m.group(2)
            if name in sets:
                value = sets[name]
                line = re.sub(r"(\.equ\s+\w+\s*,\s*)\S+", r"\g<1>" + value,
                              line)
            values[name] = int(value, 0)
        m = re.match(r"\.if\s+(\w+)$", code)
        if m:
            stack.append(bool(values[m.group(1)]))
            continue
        if code == ".else":
            stack[-1] = not stack[-1]
            continue
        if code == ".endif":
            stack.pop()
            continue
        if all(stack):
            out.append(line)
    if stack:
        raise SystemExit("unterminated .if")
    return out


def build(out_path, query=None, tests=True, sets=None):
    lines = conditionals(inline(SOURCE), sets or {})
    if query:
        lines = [re.sub(r'^query:\s*\.string\s*"[^"]*"',
                        'query:  .string "%s"' % query, l) for l in lines]
    if not tests:
        start = next(i for i, l in enumerate(lines) if l.startswith("tests:"))
        end = next(i for i, l in enumerate(lines) if l.startswith("tests_end:"))
        lines = lines[: start + 1] + lines[end:]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# GENERATED by rv32/build.py from rv32/minirubik.S. "
                "Edit the source, not this file.\n")
        f.write("\n".join(lines) + "\n")


def main(argv):
    if len(argv) == 1:
        build(os.path.join(HERE, "ripes_cli.s"))
        build(os.path.join(HERE, "ripes_gui.s"), sets={"RENDER": "1"})
        return 0
    out, query, tests, sets, i = argv[1], None, True, {}, 2
    while i < len(argv):
        if argv[i] == "--query":
            query, i = argv[i + 1], i + 2
        elif argv[i] == "--no-tests":
            tests, i = False, i + 1
        elif argv[i] == "--set":
            name, value = argv[i + 1].split("=")
            sets[name], i = value, i + 2
        else:
            raise SystemExit("unknown option " + argv[i])
    build(out, query, tests, sets)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
