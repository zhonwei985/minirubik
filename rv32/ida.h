/* IDA* solver for the 2x2x2 cube with h = max(dP, dO).
 *
 * Written the way the RV32I version will be: no heap, no recursion, no
 * multiply or divide in the search, no % 3. The same file builds for the
 * host checker and for the riscv -O2 -march=rv32i reference build.
 */
#ifndef IDA_H
#define IDA_H

#include <stdint.h>

#define IDA_MAX_MOVES 11

/* Parses "PPPPPPPOOOOOOO" (cubies 1-7, then twists 1-3) into 0-based
 * p[7], o[7]. Returns 1 when it is a valid, reachable state. */
int ida_parse(const char *in, uint8_t p[7], uint8_t o[7]);

/* Writes a shortest move sequence into moves (move = 3 * face + turns - 1,
 * faces R, B, D) and returns its length, or -1 if none within 11 moves. */
int ida_solve(const uint8_t p[7], const uint8_t o[7], uint8_t *moves);

/* Children generated by the last ida_solve, for measurement. */
extern uint32_t ida_nodes;

#endif
