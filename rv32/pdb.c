/* Two pattern databases for the 2x2x2 cube, built on the host.
 *
 * Solve two simplified cubes exactly, by the same breadth-first search
 * solver.c uses, and keep their distances as heuristic tables:
 *
 *   dP[p]  "cube A": only where each corner is (its permutation rank p,
 *          5,040 values); twists are invisible.
 *   dO[o]  "cube B": only how each corner is twisted (its twist rank o,
 *          729 values); positions are invisible.
 *
 * Any move sequence that solves the full cube also solves cube A and cube B,
 * so dP[p] <= d(p, o) and dO[o] <= d(p, o): neither overestimates, and
 * h = max(dP[p], dO[o]) does not either. This program checks that claim
 * (gate H1) against the exact distance of all 3,674,160 states, checks the
 * tables are complete (gate H2), and writes them as read-only data together
 * with the quarter-turn transition tables the search moves by:
 *
 *   OUTDIR/pdb.h     C arrays, for the host and the C reference build
 *   OUTDIR/pdb.inc   .byte / .half lines, for the RV32I assembly
 *
 *   cc -O2 -o rv32/pdb rv32/pdb.c && ./rv32/pdb rv32
 */
#include "model.h"

/* Breadth-first search from solved (rank 0) over a space of n values with a
 * move table of 9 columns. The first visit is along a shortest path, so
 * d[v] = d[u] + 1 is the exact distance. Returns the number reached. */
static uint32_t bfs(uint8_t *d, uint32_t n, uint16_t (*move)[MOVES])
{
    uint16_t *queue = malloc(n * sizeof *queue);
    uint32_t head = 0, tail = 0;
    memset(d, UNKNOWN, n);
    d[0] = 0;
    queue[tail++] = 0;
    while (head < tail) {
        uint16_t u = queue[head++];
        for (int m = 0; m < MOVES; ++m) {
            uint16_t v = move[u][m];
            if (d[v] == UNKNOWN) {
                d[v] = (uint8_t) (d[u] + 1);
                queue[tail++] = v;
            }
        }
    }
    free(queue);
    return tail;
}

static void histogram(const char *name, const uint8_t *d, uint32_t n)
{
    uint32_t count[16] = {0};
    int max = 0;
    for (uint32_t i = 0; i < n; ++i) {
        ++count[d[i]];
        max = d[i] > max ? d[i] : max;
    }
    printf("%s:", name);
    for (int k = 0; k <= max; ++k)
        printf(" %u", count[k]);
    printf("  (distance 0..%d)\n", max);
}

static int table_max(const uint8_t *d, uint32_t n)
{
    int max = 0;
    for (uint32_t i = 0; i < n; ++i)
        max = d[i] > max ? d[i] : max;
    return max;
}

/* ---- output ---------------------------------------------------------- */

static FILE *hf, *sf;
static size_t total;

static void put_u8(const char *name, const char *what, const uint8_t *v,
                   uint32_t n)
{
    fprintf(hf, "\n/* %s: %s */\nstatic const uint8_t %s[%u] = {", name, what,
            name, n);
    fprintf(sf, "# %s: %s, %u bytes\n%s:\n", name, what, n, name);
    for (uint32_t i = 0; i < n; ++i) {
        if (i % 24 == 0) {
            fprintf(hf, "\n   ");
            fprintf(sf, "    .byte ");
        }
        fprintf(hf, " %u,", v[i]);
        fprintf(sf, "%u%s", v[i], (i % 24 == 23 || i == n - 1) ? "\n" : ",");
    }
    fprintf(hf, "\n};\n");
    total += n;
}

static void put_u16(const char *name, const char *what, const uint16_t *v,
                    uint32_t rows, uint32_t n)
{
    fprintf(hf, "\n/* %s: %s */\nstatic const uint16_t %s[%u][%u] = {", name,
            what, name, rows, n);
    fprintf(sf, "# %s: %s, %u x %u halfwords\n    .align 1\n%s:\n", name, what,
            rows, n, name);
    for (uint32_t r = 0; r < rows; ++r) {
        fprintf(hf, "\n    {");
        for (uint32_t i = 0; i < n; ++i) {
            if (i % 16 == 0) {
                fprintf(hf, "\n       ");
                fprintf(sf, "    .half ");
            }
            fprintf(hf, " %u,", v[r * n + i]);
            fprintf(sf, "%u%s", v[r * n + i],
                    (i % 16 == 15 || i == n - 1) ? "\n" : ",");
        }
        fprintf(hf, "\n    },");
    }
    fprintf(hf, "\n};\n");
    total += (size_t) rows * n * 2;
}

static void emit(const char *dir, const uint8_t *dP, const uint8_t *dO)
{
    static uint16_t pt[3][PERMUTATIONS], ot[3][ORIENTATIONS];
    char path[512];
    snprintf(path, sizeof path, "%s/pdb.h", dir);
    hf = fopen(path, "w");
    snprintf(path, sizeof path, "%s/pdb.inc", dir);
    sf = fopen(path, "w");
    if (!hf || !sf) {
        fprintf(stderr, "cannot write into %s\n", dir);
        exit(1);
    }
    /* Move 3f is one quarter turn of face f; R2 and R' are that turn applied
     * again, so the search needs only these three columns. */
    for (int f = 0; f < 3; ++f) {
        for (int p = 0; p < PERMUTATIONS; ++p)
            pt[f][p] = perm_move[p][3 * f];
        for (int o = 0; o < ORIENTATIONS; ++o)
            ot[f][o] = ori_move[o][3 * f];
    }
    fprintf(hf, "/* Generated by rv32/pdb.c. Do not edit. */\n"
                "#include <stdint.h>\n");
    fprintf(sf, "# Generated by rv32/pdb.c. Do not edit.\n");
    put_u8("dP", "distance with positions only, by permutation rank", dP,
           PERMUTATIONS);
    put_u8("dO", "distance with twists only, by twist rank", dO,
           ORIENTATIONS);
    put_u16("PT", "permutation rank after a quarter turn of R, B, D",
            &pt[0][0], 3, PERMUTATIONS);
    put_u16("OT", "twist rank after a quarter turn of R, B, D", &ot[0][0], 3,
            ORIENTATIONS);
    fclose(hf);
    fclose(sf);
    printf("wrote %s/pdb.h and %s/pdb.inc: %zu bytes (dP %d, dO %d, PT %d, "
           "OT %d)\n",
           dir, dir, total, PERMUTATIONS, ORIENTATIONS, 3 * PERMUTATIONS * 2,
           3 * ORIENTATIONS * 2);
}

int main(int argc, char **argv)
{
    static uint8_t dP[PERMUTATIONS], dO[ORIENTATIONS];
    build_moves();

    /* H2: each table reaches its whole space, solved is 0, maxima known. */
    if (bfs(dP, PERMUTATIONS, perm_move) != PERMUTATIONS ||
        bfs(dO, ORIENTATIONS, ori_move) != ORIENTATIONS) {
        fputs("H2 FAIL: a table is not fully populated\n", stderr);
        return 1;
    }
    histogram("dP", dP, PERMUTATIONS);
    histogram("dO", dO, ORIENTATIONS);
    int maxP = table_max(dP, PERMUTATIONS), maxO = table_max(dO, ORIENTATIONS);
    if (dP[0] || dO[0] || maxP != 7 || maxO != 6) {
        fputs("H2 FAIL: solved entry or maximum\n", stderr);
        return 1;
    }
    printf("H2 ok: dP 5040 entries, max %d; dO 729 entries, max %d; "
           "solved entries 0\n",
           maxP, maxO);

    /* H1: h = max(dP, dO) never exceeds the exact distance. */
    uint8_t *d = exact_distances();
    uint64_t sum_h = 0, sum_d = 0;
    uint32_t exact = 0;
    for (uint32_t p = 0; p < PERMUTATIONS; ++p)
        for (uint32_t o = 0; o < ORIENTATIONS; ++o) {
            int h = dP[p] > dO[o] ? dP[p] : dO[o];
            int real = d[p * ORIENTATIONS + o];
            if (h > real) {
                fprintf(stderr, "H1 FAIL: p %u o %u: h %d > d %d\n", p, o, h,
                        real);
                return 1;
            }
            sum_h += (uint64_t) h;
            sum_d += (uint64_t) real;
            exact += h == real;
        }
    histogram("d (exact)", d, STATES);
    printf("H1 ok: max(dP, dO) <= d on all %d states; mean h %.3f, mean d "
           "%.3f; h == d on %u states (%.1f%%)\n",
           STATES, (double) sum_h / STATES, (double) sum_d / STATES, exact,
           100.0 * exact / STATES);
    free(d);

    emit(argc > 1 ? argv[1] : ".", dP, dO);
    return 0;
}
